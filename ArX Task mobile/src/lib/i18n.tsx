interface I18nContextValue {
  language: LanguageCode;
  dir: "ltr" | "rtl";
  setLanguage: (next: LanguageCode) => Promise<void>;
  t: (key: string) => string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<LanguageCode>((DEFAULT_LANGUAGE as LanguageCode) ?? "de");

  useEffect(() => {
    getLanguage().then((stored) => {
      if (stored && stored in translations) {
        setLanguageState(stored as LanguageCode);
      }
    });
  }, []);

  const setLanguage = async (next: LanguageCode) => {
    setLanguageState(next);
    await persistLanguage(next);
  };

  const value = useMemo<I18nContextValue>(
    () => ({
      language,
      dir: language === "ar" ? "rtl" : "ltr",
      setLanguage,
      t: (key: string) => translations[language][key] ?? translations.en[key] ?? key
    }),
    [language]
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error("useI18n must be used within I18nProvider");
  }

  return context;
}
